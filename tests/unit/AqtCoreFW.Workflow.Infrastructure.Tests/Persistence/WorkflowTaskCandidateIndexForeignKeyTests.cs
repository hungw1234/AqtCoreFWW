/// <summary>
/// TDD facts F1-F5 for DCAND-a: WorkflowTaskCandidateIndex → WorkflowTask FK constraint.
/// Plan: plans/260521-1008-dcand-a-candidate-index-nav-prop/phase-01-nav-prop-and-migration.md
///
/// Uses real SQL Server via Testcontainers (SqlServerCollection fixture).
/// IMPORTANT: All facts use MigrateAsync() — NOT EnsureCreatedAsync() — so they verify
/// the migration file itself, not just the in-memory EF model. Tautology guard: S5 META-L (c).
///
/// Collection-shared fixture → tests run sequentially within this collection.
/// Each test class uses its own WorkflowDbContext and handles its own schema lifecycle.
/// </summary>
[Collection(SqlServerCollection.CollectionName)]
public sealed class WorkflowTaskCandidateIndexForeignKeyTests : IAsyncLifetime
{
    private static readonly Guid TestTenantId = new("33333333-3333-3333-3333-333333333333");
    private static readonly Guid AdminUserId = new("44444444-4444-4444-4444-444444444444");

    /// <summary>Previous migration — used for F3 round-trip Down step.</summary>
    private const string PreviousMigrationName = "20260520074505_DropWorkflowTransitionRequiredPermissionCode";

    /// <summary>Target FK migration name (generated by dotnet ef migrations add).</summary>
    private const string TargetMigrationName = "AddWorkflowTaskCandidateIndexForeignKey";

    /// <summary>Expected FK constraint name per plan spec.</summary>
    private const string FkConstraintName = "FK_WorkflowTaskCandidateIndex_WorkflowTasks_WorkflowTaskId";

    private readonly SqlServerFixture _fixture;
    private WorkflowDbContext? _ctx;

    public WorkflowTaskCandidateIndexForeignKeyTests(SqlServerFixture fixture)
    {
        _fixture = fixture;
    }

    public async Task InitializeAsync()
    {
        _ctx = BuildContext();

        // MigrateAsync (not EnsureCreatedAsync): exercises real migration file chain, not just
        // in-memory EF model. Anti-tautology guard from S5 META-L (c).
        // No EnsureDeletedAsync: Testcontainers gives a fresh container per fixture lifetime.
        // On first call: creates AqtCoreFW_FkConstraintTests DB and applies all migrations.
        // On subsequent calls (other test methods): idempotent no-op (migrations already applied).
        // F3 round-trip restores DB to latest-applied state before DisposeAsync, so safe.
        await _ctx.Database.MigrateAsync();
    }

    public async Task DisposeAsync()
    {
        if (_ctx != null)
            await _ctx.DisposeAsync();
    }

    // ── F4: Orphan Pre-flight Gate ────────────────────────────────────────────────

    /// <summary>
    /// F4: Orphan pre-flight count = 0.
    /// Precondition: migrated DB, no seeded candidate-index rows.
    /// Documents the mandatory gate: FK ADD fails if orphan rows exist.
    /// Also acts as a regression test if a future seeder creates orphans.
    /// </summary>
    [Fact]
    public async Task F4_OrphanPreflightCount_IsZero_OnFreshMigratedDb()
    {
        // Precondition assert: DB has been migrated (MigrateAsync in InitializeAsync)
        var appliedMigrations = await _ctx!.Database.GetAppliedMigrationsAsync();
        appliedMigrations.Should().Contain(m => m.Contains("AddWorkflowTaskCandidateIndexForeignKey"),
            "FK migration must be applied before orphan-check is meaningful");

        // Run orphan-check SQL — same query as plan spec.
        // Use BuildTestConnectionString() to target AqtCoreFW_FkConstraintTests, not master.
        await using var conn = new SqlConnection(BuildTestConnectionString());
        await conn.OpenAsync();

        await using var cmd = conn.CreateCommand();
        cmd.CommandText = """
            SELECT COUNT(*) AS OrphanCount
            FROM workflow.WorkflowTaskCandidateIndex c
            WHERE NOT EXISTS (
                SELECT 1 FROM workflow.WorkflowTasks t WHERE t.Id = c.WorkflowTaskId
            );
            """;

        var count = (int)(await cmd.ExecuteScalarAsync())!;
        count.Should().Be(0,
            "WorkflowTaskCandidateIndex rows must all reference a valid WorkflowTask; orphan count = 0 is the FK-apply gate");
    }

    // ── F1: FK Constraint Exists After Apply ──────────────────────────────────────

    /// <summary>
    /// F1: FK constraint exists in sys.foreign_keys after migration applied.
    /// Precondition (a): clean DB with all migrations applied via MigrateAsync().
    /// Assert: FK_WorkflowTaskCandidateIndex_WorkflowTasks_WorkflowTaskId exists with count = 1.
    /// </summary>
    [Fact]
    public async Task F1_FkConstraintExists_InSysForeignKeys_AfterMigrationApplied()
    {
        // Precondition: verify migration was applied (not just model-from-EnsureCreated)
        var appliedMigrations = await _ctx!.Database.GetAppliedMigrationsAsync();
        appliedMigrations.Should().Contain(m => m.Contains("AddWorkflowTaskCandidateIndexForeignKey"),
            "pre-condition: the FK migration must appear in __EFMigrationsHistory");

        // Assert: FK exists in SQL Server metadata.
        // Use BuildTestConnectionString() to target AqtCoreFW_FkConstraintTests, not master.
        await using var conn = new SqlConnection(BuildTestConnectionString());
        await conn.OpenAsync();

        await using var cmd = conn.CreateCommand();
        cmd.CommandText = """
            SELECT COUNT(*) FROM sys.foreign_keys
            WHERE name = @fkName;
            """;
        cmd.Parameters.AddWithValue("@fkName", FkConstraintName);

        var count = (int)(await cmd.ExecuteScalarAsync())!;
        count.Should().Be(1,
            $"FK constraint '{FkConstraintName}' must exist in sys.foreign_keys after migration apply");
    }

    // ── F2: FK Rejects Orphan Insert ──────────────────────────────────────────────

    /// <summary>
    /// F2: FK rejects invalid WorkflowTaskId at DB level (proves real constraint, not model-only).
    /// Precondition (a): migrated DB; (b) no WorkflowTask with id = 999999.
    /// Action: insert WorkflowTaskCandidateIndex with WorkflowTaskId = 999999.
    /// Assert: DbUpdateException whose inner is SqlException with error number 547 (FK violation).
    /// Anti-tautology: must throw — "passes because no exception thrown" is a false-green.
    /// </summary>
    [Fact]
    public async Task F2_FkConstraint_RejectsOrphanInsert_WithSqlException547()
    {
        // Precondition (b): no WorkflowTask with id 999999
        var orphanTaskId = 999999L;
        var exists = await _ctx!.WorkflowTasks
            .IgnoreQueryFilters()
            .AnyAsync(t => t.Id == orphanTaskId);
        exists.Should().BeFalse("pre-condition: orphan reference target must not exist");

        // Action: attempt to insert candidate-index row pointing to non-existent task
        var orphanRow = WorkflowTaskCandidateIndex.Create(
            workflowTaskId: orphanTaskId,
            clauseId: 1,
            combineMode: AssignmentCombineMode.Union,
            principalType: CandidatePrincipalType.Permission,
            principalRefId: "WF.Task.Process",
            tenantId: TestTenantId);

        _ctx.WorkflowTaskCandidateIndex.Add(orphanRow);

        // Assert: FK violation raised at DB level
        // Use explicit exception inspection — FluentAssertions .Where() cannot use `is` pattern in expression trees.
        var thrownEx = await Assert.ThrowsAsync<DbUpdateException>(
            async () => await _ctx.SaveChangesAsync());

        thrownEx.Should().NotBeNull(
            "FK constraint must reject a WorkflowTaskCandidateIndex row referencing a non-existent WorkflowTask");

        var sqlEx = thrownEx.InnerException as SqlException;
        sqlEx.Should().NotBeNull("inner exception must be SqlException (FK violation at DB level)");
        sqlEx!.Number.Should().Be(547,
            "SQL Server error 547 = foreign key constraint violation (FK rejects orphan insert)");
    }

    // ── F3: Migration Round-trip Up/Down/Up ───────────────────────────────────────

    /// <summary>
    /// F3: Migration round-trip — Up→Down→Up with no errors.
    /// Proves the Down() migration is correct (DropForeignKey) and Up() is idempotent.
    /// Uses IMigrator service to apply specific migration targets.
    /// </summary>
    [Fact]
    public async Task F3_MigrationRoundTrip_UpDownUp_FkPresentAbsentPresent()
    {
        var migrator = _ctx!.Database.GetService<IMigrator>();

        // Phase 1: FK present after initial MigrateAsync() in InitializeAsync
        var fkCountAfterUp1 = await GetFkCount();
        fkCountAfterUp1.Should().Be(1, "FK must exist after initial migration apply (Up step 1)");

        // Phase 2: Down — revert to previous migration
        await migrator.MigrateAsync(PreviousMigrationName);
        var fkCountAfterDown = await GetFkCount();
        fkCountAfterDown.Should().Be(0, "FK must not exist after reverting to previous migration (Down step)");

        // Phase 3: Up — re-apply target migration
        await migrator.MigrateAsync();
        var fkCountAfterUp2 = await GetFkCount();
        fkCountAfterUp2.Should().Be(1, "FK must exist again after re-applying migration (Up step 2)");
    }

    // ── F5: WorkflowTask.Claim Rowversion Invariant Preserved ─────────────────────

    /// <summary>
    /// F5: WorkflowTask.Claim rowversion concurrency invariant preserved after nav-prop addition.
    /// Precondition: nav-prop WorkflowTaskCandidateIndex.WorkflowTask added; FK applied.
    /// Validates: WorkflowTask entity has NO tracked child navigation collection (per remarks
    /// at WorkflowTask.cs:43-48) — the nav-prop is ONE-WAY (child→parent only).
    ///
    /// Proof: (a) EF model has no reverse collection property on WorkflowTask for the
    /// candidate-index entity; (b) concurrent Claim operations on WorkflowTask in DB context
    /// stay safe (domain-level: simultaneous Claim → one wins, other throws).
    ///
    /// Note: Concurrent rowversion integration test (Claim race → DbUpdateConcurrencyException)
    /// is Phase 4 scope (ClaimTaskCommandHandler not yet implemented). This fact covers the
    /// invariant structurally: verifies no reverse ICollection was added to WorkflowTask.
    /// </summary>
    [Fact]
    public void F5_WorkflowTask_HasNoReverseCandidateIndexCollection_RowversionInvariantSafe()
    {
        // Assert: WorkflowTask entity type does NOT expose ICollection<WorkflowTaskCandidateIndex>
        var workflowTaskType = typeof(WorkflowTask);
        var reverseNavProp = workflowTaskType.GetProperties()
            .FirstOrDefault(p =>
                p.PropertyType.IsGenericType &&
                p.PropertyType.GetGenericArguments().Any(a => a == typeof(WorkflowTaskCandidateIndex)));

        reverseNavProp.Should().BeNull(
            "WorkflowTask must NOT have a reverse ICollection<WorkflowTaskCandidateIndex> nav-prop. " +
            "Adding a reverse collection would re-activate the bug-33d4973f rowversion-propagation concern " +
            "documented at WorkflowTask.cs:43-48. One-way nav (child→parent) is the required shape.");

        // Assert: WorkflowTaskCandidateIndex DOES expose the forward nav-prop
        var candidateType = typeof(WorkflowTaskCandidateIndex);
        var forwardNavProp = candidateType.GetProperty("WorkflowTask");

        forwardNavProp.Should().NotBeNull(
            "WorkflowTaskCandidateIndex must have the one-way nav-prop WorkflowTask for Phase 4 Inbox query");
        forwardNavProp!.PropertyType.Should().Be(typeof(WorkflowTask),
            "nav-prop must be WorkflowTask (nullable reference type — checked via EF null! backing)");
    }

    // ── Helpers ───────────────────────────────────────────────────────────────────

    /// <summary>
    /// Build a dedicated connection string pointing at a named test database (not master).
    /// Required so EnsureDeletedAsync + MigrateAsync operates on a safe isolated DB.
    /// Testcontainers GetConnectionString() returns master by default; we override InitialCatalog.
    /// </summary>
    private string BuildTestConnectionString()
    {
        var csb = new SqlConnectionStringBuilder(_fixture.ConnectionString)
        {
            InitialCatalog = "AqtCoreFW_FkConstraintTests",
            TrustServerCertificate = true,
            Encrypt = SqlConnectionEncryptOption.Optional,
        };
        return csb.ConnectionString;
    }

    private WorkflowDbContext BuildContext()
    {
        var options = new DbContextOptionsBuilder<WorkflowDbContext>()
            .UseSqlServer(BuildTestConnectionString(), opts =>
            {
                opts.CommandTimeout(60);
                opts.EnableRetryOnFailure(0);
            })
            .Options;

        var tenantCtx = Substitute.For<ITenantContext>();
        tenantCtx.TenantId.Returns((Guid?)TestTenantId);

        return new WorkflowDbContext(options, tenantCtx);
    }

    private async Task<int> GetFkCount()
    {
        await using var conn = new SqlConnection(BuildTestConnectionString());
        await conn.OpenAsync();
        await using var cmd = conn.CreateCommand();
        cmd.CommandText = "SELECT COUNT(*) FROM sys.foreign_keys WHERE name = @fkName;";
        cmd.Parameters.AddWithValue("@fkName", FkConstraintName);
        return (int)(await cmd.ExecuteScalarAsync())!;
    }
}
