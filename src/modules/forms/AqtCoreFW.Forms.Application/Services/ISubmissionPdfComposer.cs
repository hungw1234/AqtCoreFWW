using FluentResults;

namespace AqtCoreFW.Forms.Application.Services;

/// <summary>
/// Shared service that loads a form submission + template field labels (Dapper read-side)
/// and generates the submission PDF bytes via <see cref="IFormSubmissionPdfGenerator"/>.
///
/// Used by both the export-PDF query (download) and the sign-document command (stage for signing).
/// Centralises the Dapper SQL + JSON field-merge logic in one place (DRY).
/// </summary>
public interface ISubmissionPdfComposer
{
    /// <summary>
    /// Loads the submission (by <paramref name="submissionPublicId"/> + <paramref name="tenantId"/>),
    /// merges field labels, and generates the PDF bytes.
    /// Returns <see cref="ComposedSubmissionPdf"/> on success, or a <see cref="FluentResults.NotFoundError"/>
    /// if the submission does not exist or belongs to a different tenant.
    /// </summary>
    Task<Result<ComposedSubmissionPdf>> ComposeAsync(
        Guid submissionPublicId,
        Guid tenantId,
        CancellationToken cancellationToken = default);
}

/// <summary>
/// Result of <see cref="ISubmissionPdfComposer.ComposeAsync"/>: the generated PDF bytes
/// and the submission's public identifier (for correlation when staging for signing).
/// </summary>
public sealed record ComposedSubmissionPdf(
    /// <summary>Raw QuestPDF-generated bytes ready for download or upload to signing bucket.</summary>
    byte[] Bytes,
    /// <summary>Submission PublicId (T2 external AK) — for caller correlation, not for PDF parsing.</summary>
    Guid SubmissionPublicId);
